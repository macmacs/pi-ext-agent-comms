#!/usr/bin/env bash
# Evidence script for ticket 02: prove the shim justfile works with `just -g`.
# Every experiment runs under scratch dirs. The real ~/.config/just is never written.
set -u
E=/tmp/shim-exp/final
rm -rf "$E"
mkdir -p "$E"

run() { echo "\$ $*"; "$@"; echo "exit=$?"; echo; }
say() { echo "==== $* ===="; }

# ---- fixtures ---------------------------------------------------------------
SRC=/home/coder/repos/local/pi-ext-agent-comms
mkpkg() { # $1 = target dir, $2 = "fix" to apply the source_directory() change
  mkdir -p "$1"
  cp "$SRC/justfile" "$1/justfile"
  if [ "${2:-}" = fix ]; then sed -i 's/justfile_directory()/source_directory()/g' "$1/justfile"; fi
  mkdir -p "$1/roles"
}
mkfullpkg() { # full working tree copy (scripts/ etc.) so real recipes run
  mkdir -p "$1"
  (cd "$SRC" && tar --exclude=.git --exclude=node_modules -cf - .) | (cd "$1" && tar xf -)
  if [ "${2:-}" = fix ]; then sed -i 's/justfile_directory()/source_directory()/g' "$1/justfile"; fi
}
mkfullpkg "$E/pkg-as-is"
mkfullpkg "$E/pkg-sourcedir" fix
mkpkg "$E/pkgA" fix
mkpkg "$E/pkgB" fix
mkdir -p "$E/wk"
echo "--- repo line, package as-is today ---"; grep -n '^repo :=' "$E/pkg-as-is/justfile"
echo "--- repo line, package with the one-line fix ---"; grep -n '^repo :=' "$E/pkg-sourcedir/justfile"
echo

say "0. environment"
run just --version
echo "XDG_CONFIG_HOME=unset, HOME=$HOME"
echo "user's real global justfile (untouched by this script):"
run ls -la "$HOME/.config/just/justfile"
run readlink -f "$HOME/.config/just/justfile"

say "1. just -g search path: XDG_CONFIG_HOME/just/justfile wins"
mkdir -p "$E/xdg1/just"
printf 'import "%s/justfile"\n' "$E/pkg-sourcedir" > "$E/xdg1/just/justfile"
cd "$E/wk"
run env XDG_CONFIG_HOME="$E/xdg1" just -g --evaluate repo

say "2. search order: \$HOME/.config/just/justfile beats \$HOME/justfile"
mkdir -p "$E/fakehome/.config/just" "$E/fakehome/wk"
printf 'import "%s/justfile"\n' "$E/pkgA" > "$E/fakehome/.config/just/justfile"
printf 'import "%s/justfile"\n' "$E/pkgB" > "$E/fakehome/justfile"
cd "$E/fakehome/wk"
run env HOME="$E/fakehome" XDG_CONFIG_HOME= just -g --evaluate repo
echo "(pkgA won; pkgB would mean ~/justfile won)"
echo

say "2b. normal user case: shim at \$HOME/.config/just/justfile, XDG unset"
cat > "$E/fakehome/.config/just/justfile" <<EOF
# Managed by pi-ext-agent-comms. Generated by /coms-setup; do not edit.
# coms-setup-shim v1
import "$E/pkgA/justfile"
EOF
run cat "$E/fakehome/.config/just/justfile"
run env HOME="$E/fakehome" XDG_CONFIG_HOME= just -g --evaluate repo
run env HOME="$E/fakehome" XDG_CONFIG_HOME= just -g --list

say "3. the proposed shim with 'export PI_COMS_REPO' does NOT feed env_var_or_default"
mkdir -p "$E/xdg3/just"
cat > "$E/xdg3/just/justfile" <<EOF
export PI_COMS_REPO := "$E/pkg-sourcedir"
import "$E/pkg-as-is/justfile"
EOF
run cat "$E/xdg3/just/justfile"
cd "$E/wk"
run env XDG_CONFIG_HOME="$E/xdg3" just -g --evaluate
echo "(PI_COMS_REPO became a justfile variable, yet repo still fell back to the hardcoded ~/repos/local path)"
echo

say "4. working shim: plain import; package uses source_directory()"
mkdir -p "$E/xdg4/just"
printf 'import "%s/justfile"\n' "$E/pkg-sourcedir" > "$E/xdg4/just/justfile"
run cat "$E/xdg4/just/justfile"
cd "$E/wk"
run env XDG_CONFIG_HOME="$E/xdg4" just -g --evaluate repo
run env XDG_CONFIG_HOME="$E/xdg4" just -g --evaluate here
echo "--- same file used directly at the root (not imported) ---"
run just --justfile "$E/pkg-sourcedir/justfile" --evaluate repo
echo

say "5. justfile_directory() vs source_directory() inside an import"
mkdir -p "$E/xdg5/just" "$E/imp5"
printf 'jfd := justfile_directory()\nsrcd := source_directory()\n' > "$E/imp5/justfile"
printf 'import "%s/justfile"\n' "$E/imp5" > "$E/xdg5/just/justfile"
cd "$E/wk"
run env XDG_CONFIG_HOME="$E/xdg5" just -g --evaluate
echo "(jfd is the shim dir, srcd is the imported file's dir)"
echo

say "6. --list, --summary and real recipes through the shim"
cd "$E/wk"
run env XDG_CONFIG_HOME="$E/xdg4" just -g --list
run env XDG_CONFIG_HOME="$E/xdg4" just -g --summary
run env XDG_CONFIG_HOME="$E/xdg4" just -g respawn-demo
run env XDG_CONFIG_HOME="$E/xdg4" just -g teams
echo

say "7. settings propagate through the import"
mkdir -p "$E/xdg7/just" "$E/imp7" "$E/wk7"
cat > "$E/imp7/justfile" <<'EOF'
set dotenv-load := true
set positional-arguments

[doc("echo env + args through an import")]
show *args:
    #!/usr/bin/env bash
    set -euo pipefail
    echo "V=$V"
    echo "ARGS=$*"
EOF
printf 'import "%s/justfile"\n' "$E/imp7" > "$E/xdg7/just/justfile"
printf 'V=hello-from-dotenv\n' > "$E/wk7/.env"
cd "$E/wk7"
run cat "$E/wk7/.env"
run env XDG_CONFIG_HOME="$E/xdg7" just -g show one two
echo "--- a setting declared in the SHIM also applies to imported recipes ---"
mkdir -p "$E/xdg7b/just"
printf 'set dotenv-load := true\nimport "%s/show2.just"\n' "$E/imp7" > "$E/xdg7b/just/justfile"
printf 'show2:\n    @echo "V2=$V"\n' > "$E/imp7/show2.just"
run env XDG_CONFIG_HOME="$E/xdg7b" just -g show2
echo

say "8. working directory with -g (matters for dotenv search)"
mkdir -p "$E/imp8" "$E/xdg8/just" "$E/repo8/sub"; mkdir -p "$E/repo8/.git"
cat > "$E/imp8/justfile" <<'EOF'
pwd-here:
    @pwd
[no-cd]
pwd-invocation:
    @pwd
EOF
printf 'import "%s/justfile"\n' "$E/imp8" > "$E/xdg8/just/justfile"
cd "$E/repo8/sub"
run pwd
run env XDG_CONFIG_HOME="$E/xdg8" just -g pwd-here
run env XDG_CONFIG_HOME="$E/xdg8" just -g pwd-invocation
echo "(with -g, the recipe cwd is the VCS root of the invocation dir; [no-cd] gives the invocation dir)"
echo

say "9. alternatives that also carry PI_COMS_REPO"
echo "--- 9a. shim overrides the imported 'repo' variable (package unchanged) ---"
mkdir -p "$E/xdg9/just"
cat > "$E/xdg9/just/justfile" <<EOF
set allow-duplicate-variables
repo := "$E/pkg-as-is"
import "$E/pkg-as-is/justfile"
EOF
cd "$E/wk"
run env XDG_CONFIG_HOME="$E/xdg9" just -g --evaluate repo
echo "--- 9b. shim sets dotenv-path to a generated env file ---"
mkdir -p "$E/xdg9b/just"
printf 'PI_COMS_REPO=%s\n' "$E/pkg-as-is" > "$E/coms.env"
printf 'set dotenv-path := "%s"\nimport "%s/justfile"\n' "$E/coms.env" "$E/pkg-as-is" > "$E/xdg9b/just/justfile"
run env XDG_CONFIG_HOME="$E/xdg9b" just -g --evaluate repo
run env XDG_CONFIG_HOME="$E/xdg9b" PI_COMS_REPO=/tmp/real-env-wins just -g --evaluate repo
echo "--- 9c. same, but the env file is missing: silent wrong fallback, exit 0 ---"
mkdir -p "$E/xdg9c/just"
printf 'set dotenv-path := "%s/gone.env"\nimport "%s/justfile"\n' "$E" "$E/pkg-as-is" > "$E/xdg9c/just/justfile"
run env XDG_CONFIG_HOME="$E/xdg9c" just -g --evaluate repo
echo "--- 9d. same, with set dotenv-required: now it fails loudly ---"
mkdir -p "$E/xdg9d/just"
printf 'set dotenv-path := "%s/gone.env"\nset dotenv-required\nimport "%s/justfile"\n' "$E" "$E/pkg-as-is" > "$E/xdg9d/just/justfile"
run env XDG_CONFIG_HOME="$E/xdg9d" just -g --evaluate repo
echo

say "10. failure modes of the shim"
echo "--- 10a. plain import of a missing package: loud parse error ---"
mkdir -p "$E/xdg10/just"
printf 'import "%s/gone/justfile"\n' "$E" > "$E/xdg10/just/justfile"
run env XDG_CONFIG_HOME="$E/xdg10" just -g --list
echo "--- 10b. import? of a missing package: silent, empty recipe list, exit 0 ---"
mkdir -p "$E/xdg10b/just"
printf 'import? "%s/gone/justfile"\n' "$E" > "$E/xdg10b/just/justfile"
run env XDG_CONFIG_HOME="$E/xdg10b" just -g --list
echo "--- 10c. dangling symlink as the global justfile: loud error, no fallback ---"
mkdir -p "$E/xdg10c/just"
ln -s "$E/nowhere/justfile" "$E/xdg10c/just/justfile"
run env XDG_CONFIG_HOME="$E/xdg10c" just -g --list
echo "--- 10d. -g conflicts with JUST_JUSTFILE ---"
run env JUST_JUSTFILE=/tmp/nope/justfile XDG_CONFIG_HOME="$E/xdg4" just -g --evaluate repo
echo "--- 10e. filename is matched case-insensitively (just >= 1.42.0) ---"
mkdir -p "$E/xdg10e/just"
printf 'import "%s/justfile"\n' "$E/pkg-sourcedir" > "$E/xdg10e/just/JUSTFILE"
run env XDG_CONFIG_HOME="$E/xdg10e" just -g --evaluate repo
echo "--- 10f. relative XDG_CONFIG_HOME is ignored ---"
mkdir -p "$E/relxdg/just"
printf 'import "%s/justfile"\n' "$E/pkgB" > "$E/relxdg/just/justfile"
cd "$E/fakehome/wk"
run env HOME="$E/fakehome" XDG_CONFIG_HOME=relxdg just -g --evaluate repo
echo "(fell back to \$HOME/.config: just uses dirs::config_dir(), which needs an absolute XDG_CONFIG_HOME)"
echo

say "11. ownership: marker is inert, and how a bad writer clobbers a symlink"
mkdir -p "$E/xdg11/just"
cat > "$E/xdg11/just/justfile" <<EOF
# Managed by pi-ext-agent-comms. Generated by /coms-setup; do not edit.
# coms-setup-shim v1
import "$E/pkg-sourcedir/justfile"
EOF
run cat "$E/xdg11/just/justfile"
cd "$E/wk"
run env XDG_CONFIG_HOME="$E/xdg11" just -g --evaluate repo
echo "--- 11b. naive '> path' write follows a symlink and destroys its target ---"
mkdir -p "$E/clobber/just"
printf 'ORIGINAL: must survive\n' > "$E/clobber/target.txt"
ln -s "$E/clobber/target.txt" "$E/clobber/just/justfile"
printf 'CLOBBERED\n' > "$E/clobber/just/justfile"
run cat "$E/clobber/target.txt"
echo "--- 11c. write temp file + mv replaces the symlink itself; target survives ---"
mkdir -p "$E/safe/just"
printf 'ORIGINAL: must survive\n' > "$E/safe/target.txt"
ln -s "$E/safe/target.txt" "$E/safe/just/justfile"
printf 'SAFE shim content\n' > "$E/safe/just/.justfile.tmp"
mv -f "$E/safe/just/.justfile.tmp" "$E/safe/just/justfile"
run ls -la "$E/safe/just"
run cat "$E/safe/target.txt"
run cat "$E/safe/just/justfile"
echo

say "12. post-write check /coms-setup can run"
cd "$E/wk"
echo '$ got=$(XDG_CONFIG_HOME=... just -g --evaluate repo); [ "$got" = "<package dir>" ] && echo ok'
got=$(env XDG_CONFIG_HOME="$E/xdg11" just -g --evaluate repo)
echo "got=$got"
[ "$got" = "$E/pkg-sourcedir" ] && echo "verification ok" || echo "verification FAILED"
echo

say "13. user's real global justfile after all experiments"
run ls -la "$HOME/.config/just/justfile"
run readlink -f "$HOME/.config/just/justfile"
