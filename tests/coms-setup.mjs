async function justProblems() {
  console.log("\njust missing or too old");
  const pkg = makePackage("pkg-just");

  const xdgMissing = scratch("xdg-just-missing");
  const emptyPath = scratch("empty-path");
  const missing = await run(pkg, { xdg: xdgMissing, env: { PATH: emptyPath } });
  include("refuses a missing just", missing.out, "not found on PATH");
  check("no shim written", !fs.existsSync(path.join(xdgMissing, "just", "justfile")));

  const xdgOld = scratch("xdg-just-old");
  const fakeBin = scratch("fake-bin");
  fs.writeFileSync(path.join(fakeBin, "just"), "#!/bin/sh\necho 'just 1.30.0'\n");
  fs.chmodSync(path.join(fakeBin, "just"), 0o755);
  const old = await run(pkg, {
    xdg: xdgOld,
    env: { PATH: `${fakeBin}${path.delimiter}${process.env.PATH}` },
  });
  include("refuses an old just", old.out, "too old");
  include("prints installed vs required", old.out, "1.30.0");
  check("no shim written", !fs.existsSync(path.join(xdgOld, "just", "justfile")));
}

