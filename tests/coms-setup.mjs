const cases = [
  freshShim,
  idempotent,
  movedPackage,
  markerVersions,
  foreignFile,
  symlink,
  directory,
  devLoad,
  justProblems,
  typecheckReady,
  incompletePackage,
  baseDirMismatch,
  override,
  settingsCleanup,
];

console.log(`/coms-setup checks (fixtures in ${ROOT})`);
for (const c of cases) {
  try {
    await c();
  } catch (err) {
    failures.push(c.name);
    console.log(`  FAIL ${c.name} threw: ${err?.stack ?? err}`);
  }
}

console.log(`\n${passed} checks passed, ${failures.length} failed`);
if (failures.length > 0) {
  console.log(`failures:\n  ${failures.join("\n  ")}`);
  process.exit(1);
}
