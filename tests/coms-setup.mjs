async function settingsCleanup() {
  console.log("\nstale settings filter");
  const pkg = makePackage("pkg-settings");
  const makeSettings = (dir) => {
    fs.mkdirSync(dir, { recursive: true });
    const file = path.join(dir, "settings.json");
    fs.writeFileSync(
      file,
      JSON.stringify(
        {
          lastChangelogVersion: "0.0.0",
          packages: [
            "npm:something-else",
            { source: pkg, extensions: ["extensions/*.ts", "!extensions/coms-net.ts"] },
          ],
        },
        null,
        2,
      ) + "\n",
    );
    return file;
  };
  const listed = JSON.stringify(["extensions/*.ts", "!extensions/coms-net.ts"]);

  // No dialog: report only, never write.
  const agentA = scratch("agent-report");
  const fileA = makeSettings(agentA);
  const beforeA = fs.readFileSync(fileA, "utf8");
  const reportOnly = await run(pkg, { xdg: scratch("xdg-report"), agentDir: agentA, hasUI: false });
  include("reports the stale filter", reportOnly.out, "still carries a stale extensions filter");
  include("names the exact edit", reportOnly.out, listed);
  check("settings untouched without a dialog", fs.readFileSync(fileA, "utf8") === beforeA);

  // Dialog declined: same.
  const agentB = scratch("agent-decline");
  const fileB = makeSettings(agentB);
  const beforeB = fs.readFileSync(fileB, "utf8");
  const declined = await run(pkg, {
    xdg: scratch("xdg-decline"),
    agentDir: agentB,
    hasUI: true,
    confirm: () => false,
  });
  include("reports when declined", declined.out, "still carries a stale extensions filter");
  check("settings untouched when declined", fs.readFileSync(fileB, "utf8") === beforeB);

  // Dialog accepted: backup + clean.
  const agentC = scratch("agent-clean");
  const fileC = makeSettings(agentC);
  const cleaned = await run(pkg, {
    xdg: scratch("xdg-clean"),
    agentDir: agentC,
    hasUI: true,
    confirm: () => true,
  });
  include("reports the cleanup", cleaned.out, `cleaned the stale extensions filter in ${fileC}`);
  const after = JSON.parse(fs.readFileSync(fileC, "utf8"));
  check("entry is a plain string now", after.packages[1] === pkg, JSON.stringify(after.packages[1]));
  check("other entry untouched", after.packages[0] === "npm:something-else");
  check("other settings kept", after.lastChangelogVersion === "0.0.0");
  const backups = fs.readdirSync(agentC).filter((f) => f.startsWith("settings.json.bak-"));
  check("settings backup written", backups.length === 1, JSON.stringify(backups));
  report(
    "dialog asked for confirmation",
    cleaned.messages.some((m) => m.kind === "dialog" && m.text.includes("Clean stale coms filter?")),
  );

  // A plain-string entry has nothing to clean.
  const agentD = scratch("agent-plain");
  fs.mkdirSync(agentD, { recursive: true });
  const fileD = path.join(agentD, "settings.json");
  fs.writeFileSync(fileD, JSON.stringify({ packages: [pkg] }, null, 2) + "\n");
  const plain = await run(pkg, { xdg: scratch("xdg-plain"), agentDir: agentD, hasUI: false });
  check("no filter line for a plain entry", !plain.out.includes("extensions filter"));
}

